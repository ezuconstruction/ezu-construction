/** The project with its words in the requested language. */
export function localizeProject(p: Project, lang: 'en' | 'zh' = 'en'): Project {
  if (lang === 'en') return p;
  const z = zh[p.slug];
  return {
    ...p,
    title: z.title, type: z.type, location: z.location, summary: z.summary, story: z.story, scope: z.scope, facts: z.facts,
    galleryTitle: z.galleryTitle,
    cover: { ...p.cover, alt: z.cover },
    gallery: p.gallery.map((g, i) => ({ ...g, ...z.gallery[i] })),
    pairs: p.pairs?.map((pr, i) => ({ before: { ...pr.before, alt: z.pairs![i].before }, after: { ...pr.after, alt: z.pairs![i].after }, note: z.pairs![i].note })),
  };
}

export const projectsIn = (lang: 'en' | 'zh') => projects.map((p) => localizeProject(p, lang));
